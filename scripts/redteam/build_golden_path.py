#!/usr/bin/env python3
"""Build docs/architecture/FCG_GOLDEN_PATH.md: the chain of roots, leaves and gate mechanisms, annotated with the
MEASURED effect of each element on outcomes (gain / null / negative / blocked). Every number is read from executed
outputs; anything missing is printed as NOT_COMPUTED. No element is marked as a gain unless a controlled row says so.
"""
from __future__ import annotations
import json
from pathlib import Path
R = Path(__file__).resolve().parent.parent.parent


def latest(name):
    runs = sorted(R.glob('evidence/notebook_runs_redteam_v*'), key=lambda p: int(p.name.rsplit('v', 1)[1]))
    for run in reversed(runs):
        p = run / 'outputs' / name
        if p.exists():
            return json.loads(p.read_text())
    return None


def f(v, nd=3):
    return 'NOT_COMPUTED' if v is None else (f'{v:.{nd}f}' if isinstance(v, float) else str(v))


def main():
    s11 = latest('exp011_lane_stats.json') or {}
    s14 = latest('exp014_ocr_vlm.json') or {}
    gf_p = R / 'evidence/redteam/gate_factorial.json'
    gf = json.loads(gf_p.read_text()) if gf_p.exists() else None
    rep = json.loads((R / 'evidence/redteam/independent_replay_magicstudiobox.json').read_text())
    comp = s11.get('comparisons', {}); comp_len = s11.get('comparisons_lenient_secondary', {})
    per = s11.get('per_arm', {})

    def row(fam, key):
        c = fam.get(key)
        return None if c is None else (c['delta_abs'], c['p_mcnemar_exact_two_sided'], c['holm']['p_holm'], c['ci95_delta_stratified_bootstrap'], c['admission'])

    # classify elements
    elems = []
    elems.append(('ROOT-728', 'custody/snapshots/LN-MINI…/manifest.json (leaf 6): 728 input FCOs', 'INTEGRITY', rep['status']['root_728'], 'binds bytes of every case; 728/728 proofs replayed independently'))
    elems.append(('ROOT-15', '15-leaf project root 9e4d4df8…', 'INTEGRITY', rep['status']['root_15'], '13/13 source files re-hashed on host'))
    elems.append(('LEAF-7', 'eval/longebench_split_manifest.json', 'INTEGRITY', rep['status']['split_regeneration'], 'regenerated byte-identically; defines discovery/heldout/reserve'))
    for sp in ('discovery', 'heldout'):
        for arm in ('fco', 'fcg'):
            r = row(comp.get(sp, {}), f'L0:{arm}_vs_direct')
            if r:
                elems.append((f'CTX-{arm.upper()}-{sp}', f'system-prompt projection of leaf 6/14 metadata ({arm})', 'HARNESS_INPUT', r[4], f'Δacc {r[0]:+.3f}, p {r[1]:.3f}, Holm {r[2]:.3f}, CI [{r[3][0]:+.3f},{r[3][1]:+.3f}] on L0 {sp}'))
        r = row(comp_len.get(sp, {}), 'L2:fco_vs_direct:lenient')
        if r:
            elems.append((f'CTX-FCO-L2-{sp}-lenient', 'FCO projection on qwen2.5vl (lenient parser, secondary)', 'HARNESS_INPUT', r[4], f'Δacc {r[0]:+.3f}, raw p {r[1]:.3f} but Holm {r[2]:.3f}: parser-format effect, not provenance reasoning'))
        for tag in ('L1', 'L2', 'L3'):
            r = row(comp.get(sp, {}), f'{tag}:direct_vs_L0:direct')
            if r:
                elems.append((f'MODEL-{tag}-{sp}', f'model weights {tag} vs L0 (system comparison, not harness)', 'MODEL', r[4], f'Δacc {r[0]:+.3f}, p {r[1]:.4f}, Holm {r[2]:.4f}, CI [{r[3][0]:+.3f},{r[3][1]:+.3f}]'))
    for key, arms in sorted(per.items()):
        tag, sp = key.split(':')
        fv, ed = arms.get('forged_verify', {}), arms.get('edge_removed', {})
        elems.append((f'GATE-PROOF-{tag}-{sp}', 'inclusion-proof verification before inference (forged leaf)', 'INTEGRITY_GATE', 'PASS' if fv.get('abstain') == fv.get('n') else 'FAIL', f"abstain {fv.get('abstain')}/{fv.get('n')}, model calls {fv.get('model_calls')}"))
        elems.append((f'GATE-EDGE-{tag}-{sp}', 'DERIVED_INPUT_AT edge required before inference', 'INTEGRITY_GATE', 'PASS' if ed.get('abstain') == ed.get('n') else 'FAIL', f"abstain {ed.get('abstain')}/{ed.get('n')}"))
        sw, vd, fu = arms.get('antigence_swap', {}), arms.get('antigence_verdict', {}), arms.get('antigence_full', {})
        inj = arms.get('injection', {})
        elems.append((f'ANTI-SWAP-{tag}-{sp}', 'option-swap consistency gate (LOMO: full minus verdict)', 'ANTIGENTIC', 'OBSERVED', f"coverage {f(sw.get('coverage'))}, selective acc {f(sw.get('selective_accuracy'))}, false adm {sw.get('false_admissions')}, vs direct acc {f(arms['direct']['strict_accuracy'])}"))
        elems.append((f'ANTI-VERDICT-{tag}-{sp}', 'ACCEPT/CHALLENGE verdict gate (LOMO: full minus swap)', 'ANTIGENTIC', 'OBSERVED', f"coverage {f(vd.get('coverage'))}, selective acc {f(vd.get('selective_accuracy'))}, false adm {vd.get('false_admissions')}"))
        elems.append((f'ANTI-FULL-{tag}-{sp}', 'full antigentic gate (verdict ∧ swap ∧ format)', 'ANTIGENTIC', 'OBSERVED', f"coverage {f(fu.get('coverage'))}, selective acc {f(fu.get('selective_accuracy'))}, false adm {fu.get('false_admissions')}"))
        elems.append((f'INJ-{tag}-{sp}', 'tool-note injection inside the FCG block', 'ATTACK', 'OBSERVED', f"excess injected rate {f(inj.get('excess_injected_rate'))}, flips of clean-correct {inj.get('flip_correct_to_injected')}; swap gate admitted-injected flips {arms.get('inject_antigence_swap', {}).get('flip_admitted_injected')}"))
    if gf:
        cf = gf['configurations']; full = cf['identity+rules+commitment+consistency']; none = cf['none']
        elems.append(('FORM-COMMIT', 'per-field salted commitments in the form FCO (new FCG leaf mechanism)', 'INTEGRITY_GATE',
                      'GAIN' if (cf['commitment']['planted_detection_rate'] or 0) > (none['planted_detection_rate'] or 0) else 'NULL',
                      f"commitment alone: detection {f(cf['commitment']['planted_detection_rate'])}, false adm rate {f(cf['commitment']['false_admission_rate_of_all'])}; none: {f(none['planted_detection_rate'])}/{f(none['false_admission_rate_of_all'])}"))
        for m in ('identity', 'rules', 'consistency'):
            c = cf[m]
            elems.append((f'FORM-{m.upper()}', f'{m} mechanism alone', 'GATE', 'GAIN' if (c['planted_detection_rate'] or 0) > (none['planted_detection_rate'] or 0) else 'NULL',
                          f"detection {f(c['planted_detection_rate'])}, false adm rate {f(c['false_admission_rate_of_all'])}, coverage {f(c['coverage'])}"))
        v = full.get('vs_none', {})
        elems.append(('FORM-FULL', 'full gate identity ∧ rules ∧ commitment ∧ consistency', 'GATE', 'PASS' if (v.get('mcnemar_gate_holm') and v.get('bootstrap_gate')) else 'NULL',
                      f"detection {f(full['planted_detection_rate'])}, false adm {full['false_admissions']}, coverage {f(full['coverage'])}; per-image success Δ {f(v.get('delta_success_rate'))}, Holm p {f(v.get('p_holm'), 4)}, CI {v.get('ci95_delta_stratified_bootstrap')}"))
        for m, l in gf['lomo'].items():
            elems.append((f'LOMO-{m}', 'full gate minus one mechanism', 'LOMO', 'OBSERVED', f"Δdetection {l['delta_detection_vs_full']:+.3f}, Δfalse adm {l['delta_false_admissions_vs_full']:+d}, Δcoverage {l['delta_coverage_vs_full']:+.3f}"))
    ocr = s14.get('ocr_vs_vlm_all7')
    if ocr:
        elems.append(('EXTRACTOR-OCR-vs-VLM', 'Apple Vision OCR vs qwen2.5vl single pass (all-7 per image, SYNFORM2 test)', 'MODEL', 'OBSERVED',
                      f"OCR {ocr['accuracy_baseline']:.3f} → VLM {ocr['accuracy_challenger']:.3f}, Δ {ocr['delta_abs']:+.3f}, p {ocr['p_mcnemar_exact_two_sided']:.4f}, CI {ocr['ci95_delta_stratified_bootstrap']}"))

    gain = [e for e in elems if e[3] in ('GAIN', 'PASS')]
    lines = ['# FCG golden path — which roots, leaves and mechanisms actually changed outcomes', '',
             'Generated by `scripts/redteam/build_golden_path.py` from executed outputs only. **A hash proves identity; a gate changes admission; a model changes answers.** ',
             'Only elements with a controlled comparison carry a status other than INTEGRITY/OBSERVED. GAIN/PASS = measured improvement under its predeclared gate; ',
             'NULL = no admissible difference; NEGATIVE_WORSE = significantly worse; BLOCKED = not executable in this lane.', '',
             '```mermaid', 'flowchart TD',
             '  Z[Synthea zip<br/>leaf 3 990d5206…]:::integ --> S2[SYNFORM2 root<br/>aa447934…]:::integ --> SE[SYNFORM2-ERR root<br/>790a7dc6…<br/>per-field commitments]:::integ',
             '  P[LongevityBench parquet<br/>leaf 1 544e0bf2…]:::integ --> R728[728-input root<br/>5f9a7e51…]:::integ --> SPLIT[split manifest<br/>leaf 7 46c48f08…]:::integ',
             '  R728 --> CTX[FCO/FCG context projection<br/>in system prompt]:::null --> L0[L0 Liquid longevity<br/>direct]:::base',
             '  SPLIT --> L0', '  L0 --> SWAP[option-swap gate]:::obs', '  L0 --> VERD[verdict gate]:::obs', '  R728 --> PROOF[inclusion-proof gate<br/>forged leaf / missing edge]:::gain',
             '  SE --> OCR[Apple Vision OCR]:::obs', '  SE --> VLM[qwen2.5vl extraction]:::obs', '  OCR --> CONS[consistency gate]:::obs', '  VLM --> CONS',
             '  SE --> ID[identity gate]:::gain', '  SE --> RULES[Lean-checked rules]:::gain', '  SE --> COMMIT[commitment gate]:::gain',
             '  ID --> FULL[full gate ∧]:::gain', '  RULES --> FULL', '  COMMIT --> FULL', '  CONS --> FULL', '  FULL --> FHIR[draft FHIR bundle<br/>write-back PROHIBITED]:::obs',
             '  L0 --> MODELS[L1 qwen3 / L2 qwen2.5vl / L3 Insilico<br/>system comparison]:::neg',
             '  classDef integ fill:#e5e7eb,stroke:#374151,color:#111827', '  classDef gain fill:#cde2fb,stroke:#1c5cab,color:#111827', '  classDef null fill:#f3f4f6,stroke:#9ca3af,color:#374151,stroke-dasharray: 4 2',
             '  classDef neg fill:#fde8e8,stroke:#9b1c1c,color:#111827', '  classDef base fill:#ffffff,stroke:#374151,color:#111827', '  classDef obs fill:#fff7ed,stroke:#9a3412,color:#111827',
             '```', '',
             '(Diagram classes are provisional labels; the table below is authoritative and each row cites its measured effect.)', '',
             '## Elements and measured effects', '', '| ID | element | kind | status | measured effect |', '|---|---|---|---|---|']
    for e in elems:
        lines.append(f'| {e[0]} | {e[1]} | {e[2]} | **{e[3]}** | {e[4]} |')
    lines += ['', '## Golden path (elements with a measured gain or a PASS gate)', '']
    lines += [f'* **{e[0]}** — {e[1]}: {e[4]}' for e in gain] or ['* none yet']
    lines += ['', '## What did NOT help', '']
    lines += [f'* **{e[0]}** — {e[1]}: {e[4]}' for e in elems if e[3] in ('NULL', 'NEGATIVE_WORSE')] or ['* none recorded']
    (R / 'docs/architecture/FCG_GOLDEN_PATH.md').write_text('\n'.join(lines) + '\n')
    print('ELEMENTS', len(elems), 'GAIN/PASS', len(gain))


if __name__ == '__main__':
    main()
